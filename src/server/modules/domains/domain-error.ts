/** 工作空间 HTTP 错误（Nest ExceptionFilter 识别 code + status） */
export class DomainError extends Error {
  code: string;
  status: number;
  details?: unknown;
  constructor(code: string, message: string, status = 400, details?: unknown) {
    super(message);
    this.name = "DomainError";
    this.code = code;
    this.status = status;
    this.details = details;
  }
}
